#Exporting files
#If someone has shared a Google Drive file with you, or if you want to export a file from your own drive, here's how to do it:

#Select the file you want to export.
#Go to the file menu and choose "Download."
#Select your preferred file format. (If you're unsure, choosing the PDF format is usually a safe choice.)
#Once you've chosen a format, the file will be downloaded to your machine.

#Uploading files
#Google Drive allows you to upload your files so that you can access them from anywhere you can access your Google account. To upload files onto your drive, you need to:

#Open Google Drive and click on the "New" button.
#Choose either "File upload" or "Folder upload." (A folder is a group of files.)
#Select the files or folder you want to upload and click "Open".
#Your files will then be uploaded to your drive.