#💡 Here's how to subscribe to the study calendar:

#Open the calendar in the left sidebar on the platform, and copy your personal subscription link at the bottom.
#Click the "+" button next to "Other calendars" and choose "From URL."
#Paste the link into the "URL of Calendar" field and click "Add calendar."
#The calendar has been added, but don't leave the "Settings" page yet.
# Click on the new calendar to edit its name and set up event notifications.